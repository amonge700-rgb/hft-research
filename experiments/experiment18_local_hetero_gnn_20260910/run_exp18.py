def base_matrices(n, device):
    # EXP-015 supports 4/8.  The same transparent analytic construction is
    # extended to n=6 without claiming a new physical sample.
    if n in (4, 8):
        return graph_to_matrices(make_reference_graph(n, device=device), device=device)
    ratio = 4.0; N = 2*n; dtype = torch.float64
    A = torch.zeros((N, N), dtype=dtype, device=device)
    for off in (0, n):
        for k in range(n):
            A[off+k, off+k] = 1
            if k+1 < n: A[off+k+1, off+k] = -1
    r = torch.cat((torch.full((n,), .18/n,device=device,dtype=dtype),
                   torch.full((n,), .18/ratio**2/n,device=device,dtype=dtype)))
    leak = torch.cat((torch.full((n,),3.6e-6/n,device=device,dtype=dtype),
                      torch.full((n,),3.6e-6/ratio**2/n,device=device,dtype=dtype)))
    flux = torch.cat((torch.ones(n,device=device,dtype=dtype),
                      -torch.ones(n,device=device,dtype=dtype)/ratio))
    L = torch.diag(leak) + (220e-6/n**2)*torch.outer(flux,flux)
    C = torch.zeros((N,N),dtype=dtype,device=device)
    for off,cser,ends in ((0,72e-12,(7.,4.)),(n,42e-12,(5.,3.5))):
        for k in range(n):
            stamp_pair(C,off+k,off+k+1 if k+1<n else None,torch.tensor(cser,device=device))
            stamp_pair(C,off+k,None,torch.tensor((ends[0]+(ends[1]-ends[0])*k/(n-1))*1e-12,device=device))
    for k in range(n): stamp_pair(C,k,n+k,torch.tensor(28.36e-12/n,device=device))
    return MatrixBundle(A,torch.diag(r),L,C,torch.zeros_like(C),
                        [f"p{k}" for k in range(n)]+[f"s{k}" for k in range(n)],
                        [f"p_seg{k}" for k in range(n)]+[f"s_seg{k}" for k in range(n)],
                        torch.tensor([0,n],device=device),{"source":"EXP-015 analytic extension"})


def smooth_noise(n, gen, device, scale=.16):
    x=torch.randn(n,generator=gen,device=device,dtype=torch.float64)
    if n>2: x=(torch.roll(x,1)+2*x+torch.roll(x,-1))/4
    return scale*x/x.std().clamp_min(.3)


def make_local_sample(n, split, gen, device, target_mode="residual"):
    base=base_matrices(n,device); N=2*n; dtype=torch.float64; ratio=4.0
    # Local positive R and leakage perturbations.
    zr=torch.cat((smooth_noise(n,gen,device,.13),smooth_noise(n,gen,device,.13)))
    zl=torch.cat((smooth_noise(n,gen,device,.16),smooth_noise(n,gen,device,.16)))
    r0=torch.diag(base.R); R=torch.diag(r0*torch.exp(zr))
    leak0=torch.cat((torch.full((n,),3.6e-6/n,device=device,dtype=dtype),
                       torch.full((n,),3.6e-6/ratio**2/n,device=device,dtype=dtype)))
    leak=leak0*torch.exp(zl)
    pos=torch.arange(n,device=device,dtype=dtype)/(n-1)
    flux=torch.cat((torch.ones(n,device=device,dtype=dtype),-torch.ones(n,device=device,dtype=dtype)/ratio))
    center=torch.rand((),generator=gen,device=device,dtype=dtype)
    patch=torch.exp(-((pos-center)/.22)**2); patch=torch.cat((patch,-patch/ratio))
    flux=flux*(1+.12*patch)
    common_scale=torch.exp(.10*torch.randn((),generator=gen,device=device,dtype=dtype))
    u=torch.cat((torch.sin(math.pi*pos),-.6*torch.sin(math.pi*pos)/ratio))
    local_strength=(.06*220e-6/n**2)*torch.rand((),generator=gen,device=device,dtype=dtype)
    L=torch.diag(leak)+common_scale*(220e-6/n**2)*torch.outer(flux,flux)+local_strength*torch.outer(u,u)

    C=torch.zeros((N,N),dtype=dtype,device=device); C0=torch.zeros_like(C)
    cground=torch.zeros(N,dtype=dtype,device=device); cground0=torch.zeros_like(cground)
    local_cap=torch.zeros((N,N),dtype=dtype,device=device); local_cap0=torch.zeros_like(local_cap)
    for off,cser,ends in ((0,72e-12,(7.,4.)),(n,42e-12,(5.,3.5))):
        zc=smooth_noise(n,gen,device,.24)
        zg=smooth_noise(n,gen,device,.20)
        for k in range(n):
            cv=cser*torch.exp(zc[k]); j=off+k+1 if k+1<n else None
            stamp_pair(C,off+k,j,cv)
            stamp_pair(C0,off+k,j,torch.tensor(cser,device=device,dtype=dtype))
            if j is not None:
                local_cap[off+k,j]=local_cap[j,off+k]=cv
                local_cap0[off+k,j]=local_cap0[j,off+k]=cser
            gv=(ends[0]+(ends[1]-ends[0])*k/(n-1))*1e-12*torch.exp(zg[k])
            gv0=(ends[0]+(ends[1]-ends[0])*k/(n-1))*1e-12
            stamp_pair(C,off+k,None,gv); stamp_pair(C0,off+k,None,torch.tensor(gv0,device=device,dtype=dtype))
            cground[off+k]=gv; cground0[off+k]=gv0
    # Facing-region and nonlocal cross-winding capacitance.
    ii,jj=torch.meshgrid(pos,pos,indexing="ij")
    kernel=torch.exp(-torch.abs(ii-jj)/.42)
    ci=torch.rand((),generator=gen,device=device,dtype=dtype); cj=torch.rand((),generator=gen,device=device,dtype=dtype)
    patch2=torch.exp(-((ii-ci)/.20)**2-((jj-cj)/.20)**2)
    asym=.30*torch.randn((),generator=gen,device=device,dtype=dtype)
    cps0=kernel/kernel.sum()*28.36e-12
    cps=cps0*torch.exp(asym*patch2)
    cps=cps/cps.sum()*(28.36e-12*torch.exp(.13*torch.randn((),generator=gen,device=device,dtype=dtype)))
    for i in range(n):
        for j in range(n):
            stamp_pair(C,i,n+j,cps[i,j]); stamp_pair(C0,i,n+j,cps0[i,j])
    bundle=MatrixBundle(base.A,R,L,C,base.G,base.node_order,base.segment_order,base.external_indices,
                        {"source":"EXP-018 local synthetic perturbation"})
    nominal=MatrixBundle(base.A,base.R,base.L,C0,base.G,base.node_order,base.segment_order,base.external_indices,
                         {"source":"EXP-018 matched nominal graph"})

    # Unseen-condition test range is intentionally disjoint in phase.
    if split=="test":
        phi_deg=35+15*torch.rand((),generator=gen,device=device,dtype=dtype)
        kappa=torch.where(torch.rand((),generator=gen,device=device)>.5,
                          .80+.10*torch.rand((),generator=gen,device=device,dtype=dtype),
                          1.10+.10*torch.rand((),generator=gen,device=device,dtype=dtype))
    else:
        phi_deg=5+30*torch.rand((),generator=gen,device=device,dtype=dtype)
        kappa=.90+.20*torch.rand((),generator=gen,device=device,dtype=dtype)
    fs=15e3+15e3*torch.rand((),generator=gen,device=device,dtype=dtype)
    tr=50e-9+150e-9*torch.rand((),generator=gen,device=device,dtype=dtype)
    phi=phi_deg*math.pi/180; harmonics=torch.tensor([1,3,5,7,9],device=device,dtype=dtype)
    freqs=fs*harmonics; envelope=torch.sinc(freqs*tr)
    vp=(4*400/(math.pi*harmonics))*envelope
    vs=(4*(100*kappa)/(math.pi*harmonics))*envelope*torch.exp(-1j*harmonics*phi)
    portv=torch.stack((vp.to(torch.complex128),vs.to(torch.complex128)),1)
    sol=solve_sweep(freqs,bundle); states=recover_internal_states(sol,portv)
    sol0=solve_sweep(freqs,nominal); states0=recover_internal_states(sol0,portv)
    nodev=states["node_voltage"]/400
    nodev0=states0["node_voltage"]/400
    vals=torch.stack((sol.port_admittance[:,0,0],sol.port_admittance[:,1,1],sol.port_admittance[:,0,1]),1)
    graph_y=torch.cat((torch.log10(torch.abs(vals).clamp_min(1e-18)),torch.angle(vals)),1).float()
    node_y=torch.cat((nodev.real.T,nodev.imag.T),1).float()
    vals0=torch.stack((sol0.port_admittance[:,0,0],sol0.port_admittance[:,1,1],sol0.port_admittance[:,0,1]),1)
    graph_y0=torch.cat((torch.log10(torch.abs(vals0).clamp_min(1e-18)),torch.angle(vals0)),1).float()
    node_y0=torch.cat((nodev0.real.T,nodev0.imag.T),1).float()
    edge_y=torch.zeros((N,N),dtype=dtype,device=device); cross_mask=torch.zeros((N,N),dtype=torch.bool,device=device)
    for i in range(n):
        for j in range(n):
            cur=2*math.pi*freqs*cps[i,j]*torch.abs(nodev[:,i]-nodev[:,n+j])*400
            cur0=2*math.pi*freqs*cps0[i,j]*torch.abs(nodev0[:,i]-nodev0[:,n+j])*400
            lv=torch.log10(torch.sqrt(torch.mean(cur**2)).clamp_min(1e-12))
            lv0=torch.log10(torch.sqrt(torch.mean(cur0**2)).clamp_min(1e-12))
            edge_y[i,n+j]=edge_y[n+j,i]=lv-lv0 if target_mode=="residual" else lv
            cross_mask[i,n+j]=cross_mask[n+j,i]=True

    adj=torch.zeros((4,N,N),dtype=dtype,device=device); attr=torch.zeros((4,N,N,3),dtype=dtype,device=device)
    # series relation
    for off in (0,n):
        for k in range(n-1):
            i,j=off+k,off+k+1; adj[0,i,j]=adj[0,j,i]=1
            a=torch.stack(((zr[i]+zr[j])/2 if target_mode=="residual" else torch.log10(torch.sqrt(R[i,i]*R[j,j]))+2,
                           torch.tensor(1/(n-1),device=device,dtype=dtype),torch.tensor(1.,device=device,dtype=dtype)))
            attr[0,i,j]=attr[0,j,i]=a
    for i in range(N):
        for j in range(i+1,N):
            if local_cap[i,j]>0:
                adj[1,i,j]=adj[1,j,i]=local_cap[i,j]
                dist=torch.tensor(abs((i%n)-(j%n))/(n-1),device=device,dtype=dtype)
                value=torch.log10(local_cap[i,j]/local_cap0[i,j]) if target_mode=="residual" else torch.log10(local_cap[i,j])+12
                a=torch.stack((value,dist,torch.tensor(1.,device=device,dtype=dtype)))
                attr[1,i,j]=attr[1,j,i]=a
            if (i<n and j>=n):
                cv=cps[i,j-n]; adj[2,i,j]=adj[2,j,i]=cv
                dist=torch.tensor(abs(i-(j-n))/(n-1),device=device,dtype=dtype)
                value=torch.log10(cv/cps0[i,j-n]) if target_mode=="residual" else torch.log10(cv)+12
                a=torch.stack((value,dist,torch.tensor(1.,device=device,dtype=dtype)))
                attr[2,i,j]=attr[2,j,i]=a
            mv=L[i,j]
            if torch.abs(mv)>0:
                adj[3,i,j]=adj[3,j,i]=torch.abs(mv)
                dist=torch.tensor(abs((i%n)-(j%n))/(n-1),device=device,dtype=dtype)
                base_mv=base.L[i,j]
                value=torch.log10(torch.abs(mv/base_mv).clamp_min(1e-12)) if target_mode=="residual" else torch.log10(torch.abs(mv))+6
                a=torch.stack((value,dist,torch.sign(mv)))
                attr[3,i,j]=attr[3,j,i]=a
    for rel in range(4): adj[rel]/=adj[rel].max().clamp_min(1e-30)
    load_proxy=(400*(100*kappa)*phi*(math.pi-phi)/(2*math.pi**2*fs*3.6e-6)).clamp(0,2e5)/2e5
    cond=torch.stack((torch.log10(fs/20e3),phi/math.pi,kappa-1,tr/200e-9,load_proxy))
    winding=torch.cat((torch.zeros(n,device=device,dtype=dtype),torch.ones(n,device=device,dtype=dtype)))
    node_x=torch.stack((winding,torch.cat((pos,pos)),
                        torch.cat((torch.nn.functional.one_hot(torch.tensor(0),n).to(device,dtype),
                                   torch.nn.functional.one_hot(torch.tensor(0),n).to(device,dtype))),
                        zr if target_mode=="residual" else torch.log10(torch.diag(R))+2,
                        torch.log10(torch.diag(L)/torch.diag(base.L)) if target_mode=="residual" else torch.log10(torch.diag(L))+6,
                        torch.log10(cground/cground0) if target_mode=="residual" else torch.log10(cground)+12),1)
    node_x=torch.cat((node_x,cond.expand(N,-1)),1).float()
    if target_mode=="residual":
        graph_y=graph_y-graph_y0; node_y=node_y-node_y0
    herm=(sol.port_admittance-sol.port_admittance.transpose(-1,-2)).abs().max()
    mineig=min(torch.linalg.eigvalsh((y+y.conj().T).real/2).min() for y in sol.port_admittance)
    kcl=states["internal_kcl_residual"].abs().max()
    return Sample(n,node_x,adj.float(),attr.float(),graph_y,node_y,edge_y.float(),cross_mask,
                  {"fs_hz":float(fs),"phase_deg":float(phi_deg),"voltage_ratio_scale":float(kappa),
                   "edge_time_s":float(tr),"load_proxy":float(load_proxy),"target_mode":target_mode,
                   "reciprocity":float(herm),"min_real_y_eig":float(mineig),"kcl":float(kcl)})


class MultiTaskGNN(nn.Module):
    def __init__(self,kind,d=56,layers=3):
        super().__init__(); self.kind=kind; self.d=d
        self.enc=nn.Linear(11,d); self.norms=nn.ModuleList([nn.LayerNorm(d) for _ in range(layers)])
        self.selfs=nn.ModuleList([nn.Linear(d,d) for _ in range(layers)])
        if kind=="falcon_homogeneous": self.rel=nn.ModuleList([nn.Linear(d,d) for _ in range(layers)])
        elif kind=="hft_typed": self.rel=nn.ModuleList([nn.ModuleList([nn.Linear(d,d) for _ in range(4)]) for _ in range(layers)])
        else:
            self.rel=nn.ModuleList([nn.ModuleList([nn.Sequential(nn.Linear(2*d+3,d),nn.SiLU(),nn.Linear(d,d)) for _ in range(4)]) for _ in range(layers)])
        self.graph_head=nn.Sequential(nn.Linear(3*d,128),nn.SiLU(),nn.Linear(128,K_HARM*6))
        self.node_head=nn.Sequential(nn.Linear(d,64),nn.SiLU(),nn.Linear(64,2*K_HARM))
        self.edge_head=nn.Sequential(nn.Linear(2*d+3,64),nn.SiLU(),nn.Linear(64,1))

    def forward(self,x,adj,attr):
        h=torch.nn.functional.silu(self.enc(x)); B,R,N,_=adj.shape
        for li in range(len(self.norms)):
            msgs=[]
            if self.kind=="falcon_homogeneous":
                a=adj.sum(1); a=a/(a.sum(-1,keepdim=True)+1e-8)
                msgs=[self.rel[li](torch.bmm(a,h))]
            elif self.kind=="hft_typed":
                for r in range(4):
                    a=adj[:,r]; a=a/(a.sum(-1,keepdim=True)+1e-8)
                    msgs.append(self.rel[li][r](torch.bmm(a,h)))
            else:
                hi=h[:,:,None,:].expand(-1,-1,N,-1); hj=h[:,None,:,:].expand(-1,N,-1,-1)
                for r in range(4):
                    m=self.rel[li][r](torch.cat((hi,hj,attr[:,r]),-1))
                    mask=(adj[:,r]>0).unsqueeze(-1); den=mask.sum(2).clamp_min(1)
                    msgs.append((m*mask).sum(2)/den)
            h=self.norms[li](h+torch.nn.functional.silu(self.selfs[li](h)+sum(msgs)))
        n=N//2; pooled=torch.cat((h.mean(1),h[:,:n].mean(1),h[:,n:].mean(1)),1)
        gy=self.graph_head(pooled).reshape(B,K_HARM,6); ny=self.node_head(h)
        hi=h[:,:,None,:].expand(-1,-1,N,-1); hj=h[:,None,:,:].expand(-1,N,-1,-1)
        ey=self.edge_head(torch.cat((hi,hj,attr[:,2]),-1)).squeeze(-1)
        return gy,ny,ey


def stack(rows,device):
    return tuple(torch.stack([getattr(r,k) for r in rows]).to(device) for k in
                 ("node_x","adj","edge_attr","graph_y","node_y","edge_y","cross_mask"))


def fit_stats(rows):
    g=torch.cat([r.graph_y.reshape(-1,6) for r in rows]); nd=torch.cat([r.node_y for r in rows]);
    ed=torch.cat([r.edge_y[r.cross_mask] for r in rows])
    return {"gm":g.mean(0),"gs":g.std(0).clamp_min(1e-4),"nm":nd.mean(0),"ns":nd.std(0).clamp_min(1e-4),
            "em":ed.mean(),"es":ed.std().clamp_min(1e-4)}


def normalized_loss(pred,target,mask,stats,absolute_target):
    pg,pn,pe=pred; tg,tn,te=target
    lg=(((pg-stats["gm"])/stats["gs"]-(tg-stats["gm"])/stats["gs"])**2).mean()
    ln=(((pn-stats["nm"])/stats["ns"]-(tn-stats["nm"])/stats["ns"])**2).mean()
    le=(((pe[mask]-stats["em"])/stats["es"]-(te[mask]-stats["em"])/stats["es"])**2).mean()
    # Reciprocal output is constructed by predicting only unique Y entries.
    # Penalize negative eigenvalues of the real symmetric port admittance.
    if absolute_target:
        mag=10**pg[:,:,:3]; ph=pg[:,:,3:]; yc=mag*torch.exp(1j*ph)
        mat=torch.stack((torch.stack((yc[:,:,0],yc[:,:,2]),-1),torch.stack((yc[:,:,2],yc[:,:,1]),-1)),-2)
        eig=torch.linalg.eigvalsh(mat.real); lp=torch.relu(-eig).mean()*1e3
    else: lp=torch.zeros((),device=pg.device)
    return lg+.7*ln+.5*le+.05*lp,(lg.item(),ln.item(),le.item(),lp.item())


def train_model(model,tr,va,stats,device,epochs,batch,target_mode):
    stats={k:v.to(device) for k,v in stats.items()}; opt=torch.optim.AdamW(model.parameters(),lr=2e-3,weight_decay=2e-5)
    best=None; bestv=1e99; hist=[]; tic=time.time()
    for ep in range(epochs):
        model.train(); random.shuffle(tr); losses=[]
        for n in (4,6,8):
            sub=[r for r in tr if r.n==n]
            for q in range(0,len(sub),batch):
                x,a,e,g,nd,ey,m=stack(sub[q:q+batch],device); pred=model(x,a,e)
                loss,parts=normalized_loss(pred,(g,nd,ey),m,stats,target_mode=="absolute"); opt.zero_grad(); loss.backward(); opt.step(); losses.append(loss.item())
        model.eval(); vl=[]
        with torch.no_grad():
            for n in (4,6,8):
                sub=[r for r in va if r.n==n]
                for q in range(0,len(sub),batch):
                    x,a,e,g,nd,ey,m=stack(sub[q:q+batch],device); vl.append(normalized_loss(model(x,a,e),(g,nd,ey),m,stats,target_mode=="absolute")[0].item())
        vm=float(np.mean(vl)); hist.append([ep+1,float(np.mean(losses)),vm])
        if vm<bestv: bestv=vm; best={k:v.detach().cpu() for k,v in model.state_dict().items()}
    model.load_state_dict(best); return hist,time.time()-tic


def evaluate(model,rows,device,target_mode):
    model.eval(); rec=[]
    with torch.no_grad():
        for n in (4,6,8):
            sub=[r for r in rows if r.n==n]
            if not sub: continue
            x,a,e,g,nd,ey,m=stack(sub,device); pg,pn,pe=model(x,a,e)
            graph=(pg-g).abs().mean().item(); node=(pn-nd).abs().mean().item(); edge=(pe[m]-ey[m]).abs().mean().item()
            # Peak node is defined by RMS magnitude over natural harmonics.
            def peak(v):
                re=v[:,:,:K_HARM]; im=v[:,:,K_HARM:]
                rms=torch.sqrt((re*re+im*im).mean(-1))
                # External p0/s0 voltages are prescribed DAB conditions, not
                # meaningful internal-stress localization targets.
                rms[:,0]=-1; rms[:,n]=-1
                return torch.argmax(rms,1)
            hit=(peak(pn)==peak(nd)).float().mean().item()
            if target_mode=="absolute":
                mag=10**pg[:,:,:3]; ph=pg[:,:,3:]; yc=mag*torch.exp(1j*ph)
                mats=torch.stack((torch.stack((yc[:,:,0],yc[:,:,2]),-1),torch.stack((yc[:,:,2],yc[:,:,1]),-1)),-2)
                passive=(torch.linalg.eigvalsh(mats.real).min(-1).values>=-1e-8).float().mean().item()
            else: passive=None
            rec.append({"n":n,"graph_response_mae":graph,"node_voltage_mae":node,
                        "cross_edge_log_current_mae":edge,"peak_node_hit_rate":hit,
                        "predicted_passivity_rate":passive})
    keys=rec[0].keys(); overall={}
    for k in keys:
        if k=="n": continue
        values=[r[k] for r in rec]
        overall[k]=None if any(v is None for v in values) else float(np.mean(values))
    return overall,rec


def main():
    ap=argparse.ArgumentParser(); ap.add_argument("--device",default="cuda"); ap.add_argument("--quick",action="store_true")
    ap.add_argument("--target",choices=("absolute","residual"),default="residual")
    ap.add_argument("--seed",type=int,default=1809); args=ap.parse_args(); seed_all(args.seed)
    device=torch.device(args.device if args.device=="cpu" or torch.cuda.is_available() else "cpu")
    counts=(180,60,90) if args.quick else (720,150,240); epochs=10 if args.quick else 55
    gen=torch.Generator(device=device).manual_seed(args.seed); out=ROOT/"results"/args.target; out.mkdir(parents=True,exist_ok=True)
    rows=[]; splits=[]
    for split,count in zip(("train","val","test"),counts):
        rr=[make_local_sample((4,6,8)[i%3],split,gen,device,args.target) for i in range(count)]
        for r in rr:
            # Persist compact samples on CPU; mini-batches move back to CUDA.
            for k in ("node_x","adj","edge_attr","graph_y","node_y","edge_y","cross_mask"):
                setattr(r,k,getattr(r,k).cpu())
        rows.extend(rr); splits.append(rr)
    tr,va,te=splits; stats=fit_stats(tr)
    metrics={"experiment":"EXP-018","synthetic_only":True,"teacher":"EXP-015 exact matrix/Kron",
             "dab_representation":"natural odd PWM harmonics, not switched-device simulation",
             "device":str(device),"gpu":torch.cuda.get_device_name(0) if device.type=="cuda" else None,
             "seed":args.seed,"samples":{"train":len(tr),"val":len(va),"test":len(te)},
             "target_mode":args.target,
             "topologies":["4+4","6+6","8+8"],"relations":RELATIONS,
             "teacher_checks":{"max_reciprocity_error":max(r.meta["reciprocity"] for r in rows),
                 "minimum_real_admittance_eigenvalue":min(r.meta["min_real_y_eig"] for r in rows),
                 "max_internal_kcl_residual":max(r.meta["kcl"] for r in rows)}}
    histories={}
    for kind in ("falcon_homogeneous","hft_typed","edge_centric_hetero"):
        model=MultiTaskGNN(kind).to(device); hist,secs=train_model(model,tr,va,stats,device,epochs,24,args.target)
        overall,by=evaluate(model,te,device,args.target); metrics[kind]={**overall,"by_topology":by,
            "parameters":sum(p.numel() for p in model.parameters()),"train_seconds":secs}
        histories[kind]=hist; torch.save(model.state_dict(),out/f"{kind}.pt")
    # Save compact data contract and a reproducible subset, not the whole Python object graph.
    meta_rows=[]
    for split,rr in zip(("train","val","test"),splits):
        for i,r in enumerate(rr): meta_rows.append({"split":split,"index":i,"n":r.n,**r.meta})
    with (out/"sample_metadata.csv").open("w",newline="",encoding="utf-8-sig") as f:
        w=csv.DictWriter(f,fieldnames=meta_rows[0].keys()); w.writeheader(); w.writerows(meta_rows)
    torch.save({"samples":te[:12],"stats":stats,"seed":args.seed},out/"reproducible_test_subset.pt")
    (out/"metrics.json").write_text(json.dumps(metrics,indent=2,ensure_ascii=False),encoding="utf-8")
    for k,h in histories.items():
        with (out/f"history_{k}.csv").open("w",newline="",encoding="utf-8-sig") as f:
            w=csv.writer(f); w.writerow(["epoch","train_loss","val_loss"]); w.writerows(h)
    import matplotlib.pyplot as plt
    fig,ax=plt.subplots(figsize=(7.2,4.2))
    for k,h in histories.items(): a=np.asarray(h); ax.semilogy(a[:,0],a[:,2],label=k)
    ax.set_xlabel("Epoch"); ax.set_ylabel("Validation multi-task loss"); ax.grid(True,which="both",alpha=.25); ax.legend(); fig.tight_layout(); fig.savefig(out/"training_curves.png",dpi=220); plt.close(fig)
    labels=["FALCON homogeneous","HFT typed","Edge-centric hetero"]
    names=["falcon_homogeneous","hft_typed","edge_centric_hetero"]
    vals=np.array([[metrics[n][k] for k in ("graph_response_mae","node_voltage_mae","cross_edge_log_current_mae")] for n in names])
    fig,axs=plt.subplots(1,3,figsize=(10.2,3.8)); titles=["Port response MAE","Node voltage MAE","Cross-edge log-current MAE"]
    for j,ax in enumerate(axs): ax.bar(range(3),vals[:,j]); ax.set_xticks(range(3),["homogeneous","typed","edge-centric"],rotation=24,ha="right"); ax.set_title(titles[j]); ax.grid(True,axis="y",alpha=.25)
    fig.tight_layout(); fig.savefig(out/"test_task_comparison.png",dpi=220); plt.close(fig)
    with (out/"model_comparison.csv").open("w",newline="",encoding="utf-8-sig") as f:
        w=csv.writer(f); w.writerow(["model","graph_response_mae","node_voltage_mae","cross_edge_log_current_mae","peak_node_hit_rate","predicted_passivity_rate","parameters","train_seconds"])
        for n in names: w.writerow([n]+[metrics[n][k] for k in ("graph_response_mae","node_voltage_mae","cross_edge_log_current_mae","peak_node_hit_rate","predicted_passivity_rate","parameters","train_seconds")])
    print(json.dumps(metrics,indent=2,ensure_ascii=False))


if __name__=="__main__": main()
