"""Experiment 7: loaded multiport Cps identification under model mismatch.

The forward data are generated by a richer frequency-domain two-port model:

* frequency-dependent copper resistance and leakage inductance;
* interwinding dielectric loss;
* an additional weak cross-port RLC mode;
* asymmetric voltage/current measurement-chain responses.

The inverse model deliberately remains the compact Liu-2017-inspired mutual
admittance model used in Experiment 6.  This separates three questions:

1. Is the residual already present when the exact forward Y12 is fitted?
2. How much additional error is introduced by multi-window reconstruction and
   channel mismatch?
3. Does estimating Rs together with Ls and Cps remove the residual, or is a
   structured model-discrepancy term still left for a later AI model?

This is a model-level spectral experiment with DAB-like operating windows.  It
is not a complete switching-device DAB simulation and must not be interpreted
as hardware accuracy.
"""

from __future__ import annotations

